import { createContext, useContext, useState, ReactNode } from 'react'

export type Lang = 'ru' | 'en' | 'kz'

function storedLang(): Lang {
  try {
    const v = localStorage.getItem('sagi_lang')
    if (v === 'en' || v === 'kz') return v
    return 'ru'
  } catch { return 'ru' }
}

const Ctx = createContext<{ lang: Lang; toggle: () => void; setLang: (l: Lang) => void }>({ lang: 'ru', toggle: () => {}, setLang: () => {} })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(storedLang)
  const setLang = (next: Lang) => {
    setLangState(next)
    try { localStorage.setItem('sagi_lang', next) } catch {}
  }
  const toggle = () => {
    const order: Lang[] = ['en', 'ru', 'kz']
    const next = order[(order.indexOf(lang) + 1) % order.length]
    setLang(next)
  }
  return <Ctx.Provider value={{ lang, toggle, setLang }}>{children}</Ctx.Provider>
}

export function useLang() { return useContext(Ctx) }

